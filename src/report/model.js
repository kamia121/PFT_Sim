/**
 * Test-quality statements for the instructor appendix (grades answer questions on the learner pages, so a model built with
 * includeGrades false has none). One entry per test; each entry is a heading and its lines.
 */
function qualitySummary(caseData) {
  const out = [{ test: 'Spirometry', lines: [spirometryGradeLine(caseData).replace(/^Test quality: /, '')] }];
  const p = caseData.pleth;
  if (p) {
    const lines = [`${p.session ? `Overall lung-volume grade ${p.grade ?? 'unassigned'}; FRC ${p.session.grades.frc}, linked SVC ${p.session.grades.svc ?? 'unknown'}` : `FRCpleth simulator rubric ${p.grade} (FRC only; not an overall ATS/ERS grade)`}; ${p.repeatability?.nAcceptable ?? '?'} of ${p.repeatability?.nTrials ?? '?'} shutter closures acceptable.`];
    for (const f of p.flags ?? []) lines.push(f.text);
    out.push({ test: 'Lung volumes (plethysmography)', lines });
  }
  const g = caseData.dlcoTrace?.grade;
  if (caseData.dlcoTrace?.session) {
    const s = caseData.dlcoTrace.session;
    out.push({ test: 'DLCO', lines: [`Session ${s.status}; retained maneuvers ${s.selectedIds.join(', ') || 'none'}.`, ...s.warnings] });
  } else if (g) {
    const lines = [`Single-breath simulator rubric ${g.grade} (not an ATS/ERS session grade)${g.acceptable ? ' (acceptable)' : ' (requires review)'}.`];
    for (const [label, list] of [['Invalid', g.invalid], ['Failed criterion', g.failed], ['Noted', g.noted], ['Unconfirmed criterion', g.unknown]]) for (const x of list ?? []) lines.push(`${label}: ${x}.`);
    out.push({ test: 'DLCO', lines });
  }
  return out;
}

/**
 * Technologist comments derived from the recorded maneuvers (faults) and, when allowed, the grades. Each item carries its kind:
 * 'technical' (a fault of a maneuver), 'quality' (repeatability and grade statements, present only with includeGrades) or
 * 'interpretation' (the bronchodilator was given).
 * @returns {{ text: string, kind: 'technical'|'quality'|'interpretation' }[]}
 */
function derivedComments(caseData, includeGrades) {
  const out = [];
  const add = (text, kind) => out.push({ text, kind });
  const sets = [['Pre-bronchodilator', caseData.spirometry.pre], ['Post-bronchodilator', caseData.spirometry.post]];
  for (const [label, set] of sets) {
    if (!set) continue;
    const byFault = new Map();
    set.maneuvers.forEach((m, i) => { for (const f of m.faults) { if (!byFault.has(f)) byFault.set(f, []); byFault.get(f).push(i + 1); } });
    if (byFault.size) add(`${label}: ${[...byFault].map(([fault, idx]) => `${faultWording(fault, 'text')} (maneuver${idx.length > 1 ? 's' : ''} ${joinNumbers(idx)})`).join('; ')}.`, 'technical');
    if (!includeGrades) continue;
    const s = set.summary;
    const parts = [];
    for (const [k, name] of [['fev1', 'FEV1'], ['fvc', 'FVC']]) {
      if (s.nAcceptable[k] < 3) parts.push(`fewer than three acceptable maneuvers for ${name}`);
      else if (s.spread[k] !== null && s.spread[k] > 0.15) parts.push(`the two largest acceptable ${name} values differ by more than 0.150 L`);
    }
    add(s.repeatable && !parts.length ? `${label}: ATS/ERS repeatability criteria met for FEV1 and FVC.` : `${label}: ${parts.length ? parts.join('; ') : 'repeatability criteria not met'}. Results are interpreted with more uncertainty.`, 'quality');
    if (s.fvcAdjusted) add(`${label}: FVC reported equal to FEV1 because the largest FEV1 came from a maneuver whose FVC was not acceptable.`, 'quality');
  }
  if (caseData.spirometry.post) add('Post-bronchodilator spirometry followed an inhaled bronchodilator (agent and dose not simulated).', 'interpretation');
  return out;
}

