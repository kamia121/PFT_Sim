/** Fault observations for each trial and for the single-breath test, as note lines. */
export function trialAndTestNotes(caseData) {
  const out = [];
  for (const t of caseData.pleth?.trials ?? []) {
    const obs = trialObservation(t);
    if (obs) out.push(`Plethysmography trial ${t.index}: ${obs}.`);
  }
  const dl = (caseData.dlcoTrace?.faults ?? []).map((f) => DLCO_OBSERVATION[f.code]).filter(Boolean);
  if (dl.length) out.push(`Single-breath test: ${dl.join('; ')}.`);
  return out;
}

const REFERRERS = ['A. Okafor', 'M. Lindqvist', 'R. Castellanos', 'S. Whitfield', 'J. Nakamura', 'E. Haddad', 'P. Brennan', 'L. Moreau', 'T. Adeyemi', 'K. Novak', 'D. Ferreira', 'H. Sandoval'];
