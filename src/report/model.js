/** Deterministic test date and time (simulated, 2026) from the seed; its own stream leaves every case unchanged. */
function testDateTime(seed) {
  const rng = createStream(seed, 'report-header');
  const day = rng.int(0, 364), hour = rng.int(7, 16), minute = rng.int(0, 59);
  const d = new Date(Date.UTC(2026, 0, 1 + day));
  const p2 = (n) => String(n).padStart(2, '0');
  return { date: `${d.getUTCFullYear()}-${p2(d.getUTCMonth() + 1)}-${p2(d.getUTCDate())}`, time: `${p2(hour)}:${p2(minute)}` };
}

function paletteOf(p) {
  if (p && typeof p === 'object') return p;
  return PALETTES[p ?? 'white'] ?? PALETTES.white;
}

/** Case data in the form the figure registry reads (as src/app/render.js figureCaseData, plus what the z-score strip needs). */
export const figureCaseData = (caseData, interp, equation, resolve = null) => ({ ...caseData, interp, equation, resolve, revealed: false, showSchematic: false });

function figureSvg(id, caseData, interp, palette, equation, errors, resolve) {
  const f = FIGURES[id];
  if (!f) return '';
  try {
    const data = f.dataFor(figureCaseData(caseData, interp, equation, resolve));
    if (data === null || data === undefined) return '';
    const svg = f.render(data, { palette });
    return typeof svg === 'string' && svg.trim() ? svg : '';
  } catch (e) {
    errors.push({ id, message: String(e?.message ?? e) });
    return '';
  }
}

/** FET of the maneuver that supplies the reported FVC (largest FVC among those acceptable, else usable). */
function reportedFet(set) {
  const { maneuvers, summary } = set;
  const ev = summary.evaluations;
  let pool = maneuvers.filter((_, i) => ev[i].fvc.acceptable);
  if (!pool.length) pool = maneuvers.filter((_, i) => ev[i].fvc.usable);
  if (!pool.length) return null;
  return pool.reduce((a, b) => (b.fvc > a.fvc ? b : a)).fet;
}

