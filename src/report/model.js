/**
 * Report model: the simulated case laid out as an ATS 2017 standardized pulmonary function report
 * (Culver et al., AJRCCM 2017;196:1463). The model is plain JSON with no HTML. `html.js` renders it
 * and `export.js` derives CSV, TSV and clipboard HTML from the same tables, so the outputs agree.
 *
 * Layout rules taken from docs/research/report-formats.md: measured value first, then the lower limit
 * of normal, then the z-score, then percent predicted; the predicted value itself is omitted; the
 * lower limit is not repeated after the bronchodilator; change columns appear only for FEV1 and FVC;
 * the ratio is a decimal with a blank percent-predicted cell; one footnote line under each table names
 * the reference equation and the test-quality grades. Values are not flagged, because a flag turns a
 * continuous variable into a binary one. Change is computed from the displayed (rounded) values, so a
 * printed change always equals the difference of the printed best values.
 *
 * Nothing in the model comes from the answer key or the ground truth. Grades, per-maneuver
 * acceptability and comments derived from them are included only when `includeGrades` is true (the
 * default, as on a real report); the learner page passes false until answers are checked.
 */
