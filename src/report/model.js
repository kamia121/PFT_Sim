/**
 * Report model: the simulated case laid out as an ATS 2017 standardized pulmonary function report
 * (Culver et al., AJRCCM 2017;196:1463). The model is plain JSON with no HTML. `html.js` renders it
 * and `export.js` derives CSV, TSV and clipboard HTML from the same tables, so the outputs agree.
 *
 * Layout rules taken from docs/research/report-formats.md: measured value first, then the lower limit
 * of normal, then the z-score, then percent predicted; the predicted value itself is omitted; the
 * lower limit is not repeated after the bronchodilator; change columns appear only for FEV1 and FVC;
 * the ratio is a decimal with a blank percent-predicted cell; one footnote line under each table names
 * the reference equation and the test-quality grades. Values are not flagged, because a flag turns a
 * continuous variable into a binary one. Change is computed from the displayed (rounded) values, so a
 * printed change always equals the difference of the printed best values.
 *
 * Nothing in the model comes from the answer key or the ground truth. Grades, per-maneuver
 * acceptability and comments derived from them are included only when `includeGrades` is true (the
 * default, as on a real report); the learner page passes false until answers are checked.
 */
import { LLN_Z } from '../interpret/interpret.js';
import { GENERATOR_VERSION } from '../core/standards.js';
import { createStream } from '../core/prng.js';
import { PALETTES } from '../ui/palettes.js';
import { FIGURES } from '../ui/figures/index.js';
import { EQUATION_NAMES, hbKnown, coHbMeasured, coHbUnmeasured, sexUndisclosed } from '../app/format.js';
import { round } from './table.js';
import { faultWording } from '../core/quality.js';

export const SIMULATION_DISCLAIMER = 'Simulated report generated by PFT Sim for teaching. Values are synthetic and uncalibrated. This is not a patient record and must not be used for clinical decisions.';
/** Short marker carried by every export (first row of a CSV, caption line of a TSV or clipboard table) and by the print watermark. */
export const SIMULATION_MARKER = 'SIMULATED REPORT - educational use only';
export const LLN_TEXT = `Lower limit of normal (LLN): z-score of ${String(LLN_Z).replace('-', '−')}, the 5th percentile of the reference population.`;

/** Case code used in file names: the seed in base 36, 7 characters. */
export const caseCode = (seed) => Number(seed).toString(36).toUpperCase().padStart(7, '0');
/** Patient ID printed on the report. The SIM- prefix marks it as synthetic and unlike any real identifier. */
export const patientId = (seed) => `SIM-${caseCode(seed)}`;

const SEX = { M: 'Male', F: 'Female' };
const HEIGHT_SOURCE = { measured: 'measured', 'arm-span': 'estimated from arm span', ulna: 'estimated from ulna length', reported: 'patient-reported' };
const FIGURE_PLAN = { spirometry: ['flow-volume', 'volume-time', 'z-strip'], volumes: ['pleth-shutter', 'pleth-raw'], dlco: ['dlco-trace'] };

const eqName = (id) => EQUATION_NAMES[id] ?? id;
const bmiOf = (p) => p.weightKg / (p.heightCm / 100) ** 2;
const joinNumbers = (xs) => (xs.length === 1 ? `${xs[0]}` : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`);

/** Deterministic test date and time (simulated, 2026) from the seed; its own stream leaves every case unchanged. */
function testDateTime(seed) {
  const rng = createStream(seed, 'report-header');
  const day = rng.int(0, 364), hour = rng.int(7, 16), minute = rng.int(0, 59);
  const d = new Date(Date.UTC(2026, 0, 1 + day));
  const p2 = (n) => String(n).padStart(2, '0');
  return { date: `${d.getUTCFullYear()}-${p2(d.getUTCMonth() + 1)}-${p2(d.getUTCDate())}`, time: `${p2(hour)}:${p2(minute)}` };
}

function paletteOf(p) {
  if (p && typeof p === 'object') return p;
  return PALETTES[p ?? 'white'] ?? PALETTES.white;
}

function figureSvg(id, caseData, interp, palette, equation, errors) {
  const f = FIGURES[id];
  if (!f) return '';
  try {
    const data = f.dataFor(caseData, interp, { equation });
    if (data === null || data === undefined) return '';
    const svg = f.render(data, { palette });
    return typeof svg === 'string' && svg.trim() ? svg : '';
  } catch (e) {
    errors.push({ id, message: String(e?.message ?? e) });
    return '';
  }
}

/** FET of the maneuver that supplies the reported FVC (largest FVC among those acceptable, else usable). */
function reportedFet(set) {
  const { maneuvers, summary } = set;
  const ev = summary.evaluations;
  let pool = maneuvers.filter((_, i) => ev[i].fvc.acceptable);
  if (!pool.length) pool = maneuvers.filter((_, i) => ev[i].fvc.usable);
  if (!pool.length) return null;
  return pool.reduce((a, b) => (b.fvc > a.fvc ? b : a)).fet;
}

const spirometryGradeLine = (caseData) => {
  const pre = caseData.spirometry.pre.summary.grades, post = caseData.spirometry.post?.summary.grades;
  return `Test quality: Pre: FEV1 - ${pre.fev1}, FVC - ${pre.fvc}${post ? `; Post: FEV1 - ${post.fev1}, FVC - ${post.fvc}` : ''}.`;
};

/** Technologist comments derived from the recorded maneuvers (faults) and, when allowed, the grades. */
function derivedComments(caseData, includeGrades) {
  const out = [];
  const sets = [['Pre-bronchodilator', caseData.spirometry.pre], ['Post-bronchodilator', caseData.spirometry.post]];
  for (const [label, set] of sets) {
    if (!set) continue;
    const byFault = new Map();
    set.maneuvers.forEach((m, i) => { for (const f of m.faults) { if (!byFault.has(f)) byFault.set(f, []); byFault.get(f).push(i + 1); } });
    if (byFault.size) out.push(`${label}: ${[...byFault].map(([fault, idx]) => `${faultWording(fault, 'text')} (maneuver${idx.length > 1 ? 's' : ''} ${joinNumbers(idx)})`).join('; ')}.`);
    if (!includeGrades) continue;
    const s = set.summary;
    const parts = [];
    for (const [k, name] of [['fev1', 'FEV1'], ['fvc', 'FVC']]) {
      if (s.nAcceptable[k] < 3) parts.push(`fewer than three acceptable maneuvers for ${name}`);
      else if (s.spread[k] !== null && s.spread[k] > 0.15) parts.push(`the two largest acceptable ${name} values differ by more than 0.150 L`);
    }
    out.push(s.repeatable && !parts.length ? `${label}: ATS/ERS repeatability criteria met for FEV1 and FVC.` : `${label}: ${parts.length ? parts.join('; ') : 'repeatability criteria not met'}. Results are interpreted with more uncertainty.`);
    if (s.fvcAdjusted) out.push(`${label}: FVC reported equal to FEV1 because the largest FEV1 came from a maneuver whose FVC was not acceptable.`);
  }
  if (caseData.spirometry.post) out.push('Post-bronchodilator spirometry followed an inhaled bronchodilator (agent and dose not simulated).');
  return out;
}

/** Plethysmography replicates from case.pleth.replicateTable (src/core/pleth.js); other field names are accepted for tests. */
function plethRows(pleth) {
  const list = pleth?.replicateTable ?? pleth?.replicates ?? pleth?.trials ?? pleth?.efforts ?? pleth?.determinations ?? null;
  if (!Array.isArray(list) || !list.length) return null;
  const val = (t) => t.frcL ?? t.frc ?? t.frcPleth ?? t.tgv ?? t.value ?? null;
  const hz = (t) => t.panFreqHz ?? t.pantHz ?? t.panHz ?? t.frequencyHz ?? t.hz ?? null;
  const vals = list.map(val).filter((v) => Number.isFinite(v));
  // The reported FRC is the mean of the acceptable trials, which the plethysmography model supplies.
  const mean = Number.isFinite(pleth?.reportedFrcL) ? pleth.reportedFrcL : vals.length ? vals.reduce((a, b) => a + b, 0) / vals.length : null;
  return { list, val, hz, mean, vals };
}

/**
 * @param {object} caseData result of buildCase
 * @param {object} interp result of interpret(caseData.report, resolve, equation)
 * @param {{ equation?: 'GLI2012'|'GLIglobal', includeKey?: boolean, includeGrades?: boolean, interpretationText?: string|null,
 *   resolve?: Function, palette?: string|object, figures?: boolean }} [options]
 *   `resolve` (resolveReference) supplies post-bronchodilator z-scores; without it those cells are blank.
 * @returns {object} see docs/ARCHITECTURE-NEXT.md, with the additions documented in this file
 */
export function buildReportModel(caseData, interp, options = {}) {
  const equation = options.equation ?? interp.spirometryEquation;
  if (interp.spirometryEquation && equation !== interp.spirometryEquation) throw new RangeError(`interp was computed with ${interp.spirometryEquation}, not ${equation}`);
  const includeGrades = options.includeGrades !== false;
  const includeKey = options.includeKey === true;
  const resolve = options.resolve ?? null;
  const palette = paletteOf(options.palette);
  const wantFigures = options.figures !== false;
  const figureErrors = [];

  const d = caseData.descriptor, patient = caseData.report.patient, scenario = caseData.scenario ?? null;
  const m = interp.measures;
  const code = caseCode(d.seed);
  const sp = caseData.report.spirometry, post = sp.post;
  const hasPost = Boolean(post && caseData.spirometry.post);
  const when = testDateTime(d.seed);

  // ---------------- reference-equation resolution, as laboratory practice would state it ----------------
  const volEq = m.tlc?.equationId ?? 'GLI2021vol', tlcoEq = m.dlco?.equationId ?? 'GLI2017tlco';
  const volMatched = m.tlc?.matched !== false, tlcoMatched = m.dlco?.matched !== false;
  const fallbackText = (matched) => (matched ? '' : ' (reference population of European ancestry)');

  // ---------------- header ----------------
  const hs = scenario?.height;
  const heightSource = HEIGHT_SOURCE[hs?.source ?? 'measured'] ?? hs?.source;
  const undisclosedSex = sexUndisclosed(scenario);
  // Sex assigned at birth is shown only when it differs from the reference sex, and never when the patient declined to give a sex.
  const birthSex = undisclosedSex ? undefined : scenario?.referenceSex?.birth;
  const tests = ['Spirometry', ...(hasPost ? ['bronchodilator study'] : []), ...(caseData.volumes ? ['lung volumes (plethysmography)'] : []), ...(caseData.dlco ? ['DLCO (single breath)'] : [])];
  const eqLines = [`Spirometry: ${eqName(equation)}`];
  if (caseData.volumes) eqLines.push(`Lung volumes: ${eqName(volEq)}`);
  if (caseData.dlco) eqLines.push(`DLCO: ${eqName(tlcoEq)}`);
  const ambient = caseData.ambient ?? scenario?.ambient ?? null;
  const smoking = scenario?.smokingStatus ?? null;
  const fields = [
    { label: 'Name', value: 'Simulated patient' },
    { label: 'ID', value: patientId(d.seed) },
    { label: 'Sex (used for reference)', value: undisclosedSex ? `${SEX[patient.sex]} (laboratory default; sex not disclosed)` : SEX[patient.sex] },
    ...(birthSex && birthSex !== patient.sex ? [{ label: 'Sex assigned at birth', value: SEX[birthSex] }] : []),
    { label: 'Age', value: `${patient.age} years` },
    { label: 'Height', value: `${patient.heightCm} cm (${heightSource})` },
    { label: 'Weight', value: `${patient.weightKg} kg` },
    { label: 'BMI', value: `${bmiOf(patient).toFixed(1)} kg/m2` },
    { label: 'Reference group', value: patient.group },
    ...(smoking ? [{ label: 'Smoking status', value: smoking }] : []),
    ...(caseData.dlco ? [{ label: 'Hemoglobin', value: hbKnown(caseData.dlco) ? `${caseData.dlco.hbGdl.toFixed(1)} g/dL` : 'not available' }] : []),
    { label: 'Test date (simulated)', value: `${when.date} ${when.time}` },
    ...(ambient ? [{ label: 'Ambient conditions', value: [ambient.temperatureC !== undefined && `${ambient.temperatureC} °C`, ambient.pressureMmHg !== undefined && `Pb ${ambient.pressureMmHg} mmHg`].filter(Boolean).join('; ') }] : []),
    { label: 'Tests performed', value: tests.join('; ') },
    { label: 'Reference equations', value: eqLines.join('; ') },
    { label: 'LLN definition', value: `z = ${String(LLN_Z).replace('-', '−')}` },
  ];

  // ---------------- spirometry ----------------
  const preSet = caseData.spirometry.pre, postSet = caseData.spirometry.post;
  const G1 = 'Pre-bronchodilator', G2 = 'Post-bronchodilator';
  const spCols = [
    { key: 'index', label: 'Index', align: 'left' },
    { key: 'pre', label: 'Best', group: G1, rowDp: true, unit: 'row' },
    { key: 'lln', label: 'LLN', group: G1, rowDp: true, unit: 'row' },
    { key: 'z', label: 'z-score', group: G1, dp: 2 },
    { key: 'pct', label: '%Pred', group: G1, dp: 0 },
    ...(hasPost ? [
      { key: 'post', label: 'Best', group: G2, rowDp: true, unit: 'row' },
      { key: 'postZ', label: 'z-score', group: G2, dp: 2 },
      { key: 'postPct', label: '%Pred', group: G2, dp: 0 },
      { key: 'change', label: 'Change', group: G2, rowDp: true, signed: true, unit: 'row' },
      { key: 'changePct', label: '% change of baseline', group: G2, dp: 1, signed: true },
      { key: 'changePctPred', label: 'Change, % of predicted', group: G2, dp: 1, signed: true },
    ] : []),
  ];
  const postRef = (measure, measured) => {
    if (!resolve || !(measured > 0)) return null;
    const r = resolve(measure, { ...patient, measured }, equation);
    return r.available ? r : null;
  };
  const spRow = (id, label, unit, dp) => {
    const r = m[id];
    const row = { id, index: label, unit, dp, pre: round(r?.value, dp), lln: null, z: null, pct: null };
    if (r && r.available !== false) {
      row.lln = round(r.lln, dp); row.z = round(r.z, 2);
      row.pct = id === 'fev1_fvc' ? null : round(r.percentPredicted, 0);
    }
    if (hasPost) {
      const pv = id === 'fev1_fvc' ? post.fev1 / post.fvc : post[id];
      Object.assign(row, { post: round(pv, dp), postZ: null, postPct: null, change: null, changePct: null, changePctPred: null });
      const ref = r && r.available !== false ? postRef(id, pv) : null;
      if (ref) row.postZ = round(ref.z, 2);
      if (id !== 'fev1_fvc' && r && r.available !== false) {
        row.postPct = round((100 * row.post) / r.predicted, 0);
        row.change = round(row.post - row.pre, dp);
        row.changePct = round((100 * row.change) / row.pre, 1);
        row.changePctPred = round((100 * row.change) / r.predicted, 1);
      }
    }
    return row;
  };
  const extraRow = (id, label, unit, dp, preVal, postVal) => ({ id, index: label, unit, dp, pre: round(preVal, dp), lln: null, z: null, pct: null, ...(hasPost ? { post: round(postVal, dp), postZ: null, postPct: null, change: null, changePct: null, changePctPred: null } : {}) });
  const spRows = [
    spRow('fvc', 'FVC', 'L', 2), spRow('fev1', 'FEV1', 'L', 2), spRow('fev1_fvc', 'FEV1/FVC', 'ratio', 3),
    extraRow('fet', 'FET', 's', 1, reportedFet(preSet), postSet ? reportedFet(postSet) : null),
    extraRow('pef', 'PEF', 'L/s', 1, preSet.summary.pef, postSet?.summary.pef ?? null),
  ];
  const spFootParts = [`Reference values: ${eqName(equation)}${equation === 'GLI2012' ? ` (equation for "${patient.group}")` : ' (group-neutral)'}.`];
  spFootParts.push(includeGrades ? spirometryGradeLine(caseData) : 'Test quality: grades are shown after the answers are checked.');
  const spTable = { id: 'spirometry', caption: 'Spirometry', columns: spCols, rows: spRows, footnote: spFootParts.join(' ') };

  const maneuverTable = (set, id, caption) => {
    const cols = [
      { key: 'index', label: 'No.', align: 'left' },
      { key: 'fvc', label: 'FVC', unit: 'L', dp: 2 },
      { key: 'fev1', label: 'FEV1', unit: 'L', dp: 2 },
      { key: 'pef', label: 'PEF', unit: 'L/s', dp: 1 },
      { key: 'fet', label: 'FET', unit: 's', dp: 1 },
      { key: 'bev', label: 'BEV', unit: 'L', dp: 3 },
      ...(includeGrades ? [{ key: 'acceptable', label: 'Accept.', align: 'left' }] : []),
      { key: 'comment', label: 'Comment', align: 'left' },
    ];
    const rows = set.maneuvers.map((mv, i) => {
      const ev = set.summary.evaluations[i];
      const acc = ['fev1', 'fvc'].filter((k) => ev[k].acceptable).map((k) => k.toUpperCase());
      return {
        id: String(i + 1), index: String(i + 1), fvc: round(mv.fvc, 2), fev1: round(mv.fev1, 2), pef: round(mv.pef, 1), fet: round(mv.fet, 1), bev: round(mv.bev, 3),
        ...(includeGrades ? { acceptable: acc.length === 2 ? 'both' : acc.length ? acc[0] : 'neither' } : {}),
        comment: mv.faults.map((f) => faultWording(f, 'short')).join(', '),
      };
    });
    return { id, caption, columns: cols, rows, footnote: `BEV: back-extrapolated volume. ${includeGrades ? 'Accept.: variable(s) for which the maneuver meets ATS/ERS 2019 criteria.' : 'Acceptability is shown after the answers are checked.'}` };
  };
  const spTables = [spTable, maneuverTable(preSet, 'maneuvers-pre', 'Forced maneuvers before bronchodilator')];
  if (hasPost) spTables.push(maneuverTable(postSet, 'maneuvers-post', 'Forced maneuvers after bronchodilator'));

  const sections = [{ id: 'spirometry', title: 'Spirometry', tables: spTables, figures: [], figureIds: [], notes: [] }];

  // ---------------- lung volumes ----------------
  if (caseData.volumes) {
    const volRow = (id, label, unit, dp) => {
      const r = m[id];
      const row = { id, index: label, unit, dp, result: round(r?.value, dp), lln: null, uln: null, z: null, pct: null };
      if (r && r.available !== false) Object.assign(row, { lln: round(r.lln, dp), uln: round(r.uln, dp), z: round(r.z, 2), pct: id === 'rv_tlc' ? null : round(r.percentPredicted, 0) });
      return row;
    };
    const cols = [
      { key: 'index', label: 'Index', align: 'left' },
      { key: 'result', label: 'Result', rowDp: true, unit: 'row' },
      { key: 'lln', label: 'LLN', rowDp: true, unit: 'row' },
      { key: 'uln', label: 'ULN', rowDp: true, unit: 'row' },
      { key: 'z', label: 'z-score', dp: 2 },
      { key: 'pct', label: '%Pred', dp: 0 },
    ];
    const rows = [volRow('tlc', 'TLC', 'L', 2), volRow('vc', 'VC', 'L', 2), volRow('ic', 'IC', 'L', 2), volRow('frc', 'FRC', 'L', 2), volRow('erv', 'ERV', 'L', 2), volRow('rv', 'RV', 'L', 2), volRow('rv_tlc', 'RV/TLC', '%', 1)];
    const pl = plethRows(caseData.pleth);
    const volFoot = `Reference values: ${eqName(volEq)}${fallbackText(volMatched)}. Method: plethysmography${pl ? ` (${pl.list.length} FRC determinations)` : ', single determination'}. ULN: z = +1.645.`;
    const tables = [{ id: 'volumes', caption: 'Lung volumes', columns: cols, rows, footnote: volFoot }];
    if (pl) {
      const pcols = [
        { key: 'index', label: 'Determination', align: 'left' },
        { key: 'frc', label: 'FRCpleth', unit: 'L', dp: 2 },
        { key: 'hz', label: 'Pant frequency', unit: 'Hz', dp: 2 },
        { key: 'dev', label: 'Difference from mean', unit: '%', dp: 1, signed: true },
        ...(includeGrades ? [{ key: 'acceptable', label: 'Acceptable', align: 'left' }] : []),
      ];
      const prow = pl.list.map((t, i) => ({
        id: String(i + 1), index: String(i + 1), frc: round(pl.val(t), 2), hz: round(pl.hz(t), 2),
        dev: pl.mean ? round((100 * (pl.val(t) - pl.mean)) / pl.mean, 1) : null,
        ...(includeGrades ? { acceptable: t.acceptable === undefined ? '' : t.acceptable ? 'yes' : 'no' } : {}),
      }));
      const spread = pl.vals.length > 1 ? (100 * (Math.max(...pl.vals) - Math.min(...pl.vals))) / pl.mean : null;
      const bits = [pl.mean !== null && `Mean FRCpleth ${pl.mean.toFixed(2)} L`, spread !== null && `repeatability (highest minus lowest, over mean) ${spread.toFixed(1)}%`, includeGrades && caseData.pleth.grade && `grade ${caseData.pleth.grade}`].filter(Boolean);
      tables.push({ id: 'pleth', caption: 'Plethysmography replicate determinations', columns: pcols, rows: prow, footnote: `${bits.join('; ')}.` });
    }
    sections.push({ id: 'volumes', title: 'Lung volumes', tables, figures: [], figureIds: [], notes: [] });
  }

  // ---------------- diffusing capacity ----------------
  if (caseData.dlco) {
    const dl = caseData.dlco;
    const refRow = (id, label, unit, dp) => {
      const r = m[id];
      const row = { id, index: label, unit, dp, result: round(r?.value, dp), lln: null, z: null, pct: null };
      if (r && r.available !== false) Object.assign(row, { lln: round(r.lln, dp), z: round(r.z, 2), pct: round(r.percentPredicted, 0) });
      return row;
    };
    const plain = (id, label, unit, dp, v) => ({ id, index: label, unit, dp, result: round(v, dp), lln: null, z: null, pct: null });
    const cols = [
      { key: 'index', label: 'Index', align: 'left' },
      { key: 'result', label: 'Result', rowDp: true, unit: 'row' },
      { key: 'lln', label: 'LLN', rowDp: true, unit: 'row' },
      { key: 'z', label: 'z-score', dp: 2 },
      { key: 'pct', label: '%Pred', dp: 0 },
    ];
    const hbOk = hbKnown(dl);
    const trace = caseData.dlcoTrace ?? null;
    const rows = [
      plain('dlco-raw', hbOk ? 'DLCO, unadjusted' : 'DLCO, measured (no Hb adjustment)', 'mL/min/mmHg', 1, dl.raw),
      hbOk ? plain('hb', 'Hemoglobin', 'g/dL', 1, dl.hbGdl) : { id: 'hb', index: 'Hemoglobin', unit: 'g/dL', dp: 1, result: 'not available', lln: null, z: null, pct: null },
      ...(hbOk ? [plain('hb-factor', 'Hb adjustment factor', '', 3, dl.hbFactor)] : []),
      refRow('dlco', hbOk ? 'DLCO, Hb-adjusted' : 'DLCO, unadjusted (Hb not available)', 'mL/min/mmHg', 1),
      refRow('va', 'VA', 'L', 2),
      refRow('kco', 'KCO', 'mL/min/mmHg/L', 2),
      ...(Number.isFinite(trace?.inspired?.viOverVc) ? [plain('vi-vc', 'VI/VC', '%', 0, 100 * trace.inspired.viOverVc)] : []),
      ...(Number.isFinite(trace?.breathHold?.seconds) ? [plain('breath-hold', 'Breath-hold time', 's', 1, trace.breathHold.seconds)] : []),
    ];
    // Carboxyhemoglobin is reported only when it was measured; otherwise the line says that it was not.
    const coHbLine = coHbMeasured(scenario) ? `COHb ${scenario.coHbPercent.toFixed(1)}%; DLCO is not adjusted for COHb.`
      : coHbUnmeasured(scenario) ? 'COHb was not measured; the DLCO may be underestimated if smoking was recent.' : null;
    const foot = [
      `Reference values: ${eqName(tlcoEq)}${fallbackText(tlcoMatched)}. LLN, z-score and %Pred refer to the ${hbOk ? 'Hb-adjusted DLCO (Cotes formula, not yet checked against the 2017 ERS/ATS standard)' : 'DLCO without hemoglobin adjustment, because no hemoglobin was available'}.`,
      ambient?.pressureMmHg !== undefined ? `Pb: ${ambient.pressureMmHg} mmHg.` : null,
      coHbLine,
      trace ? 'Inspired volume (VI/VC) and breath-hold time are simulated from the tracing; replicate tests are not simulated.' : 'Replicate tests are not simulated.',
    ].filter(Boolean).join(' ');
    sections.push({ id: 'dlco', title: 'Diffusing capacity', tables: [{ id: 'dlco', caption: 'Single-breath DLCO', columns: cols, rows, footnote: foot }], figures: [], figureIds: [], notes: [] });
  }

  // ---------------- figures ----------------
  if (wantFigures) {
    for (const s of sections) {
      for (const id of FIGURE_PLAN[s.id] ?? []) {
        const svg = figureSvg(id, caseData, interp, palette, equation, figureErrors);
        if (svg) { s.figures.push(svg); s.figureIds.push(id); }
      }
    }
  }

  // ---------------- reference equation note ----------------
  const note = [];
  note.push(equation === 'GLIglobal'
    ? 'Spirometry reference: GLI Global 2022, a group-neutral equation; the reference group on the requisition is not an input.'
    : `Spirometry reference: GLI-2012 equation for the requisition group "${patient.group}".`);
  const fallbacks = [caseData.volumes && !volMatched && 'GLI-2021 volume', caseData.dlco && !tlcoMatched && 'GLI-2017 TLCO'].filter(Boolean);
  if (fallbacks.length) note.push(`The ${fallbacks.join(' and ')} equation${fallbacks.length > 1 ? 's were' : ' was'} derived in people of European ancestry, so the reference population may represent the group "${patient.group}" less well; this limits the result, and no ancestry adjustment is applied to volumes or DLCO.`);
  if (hs && hs.source !== 'measured') note.push(`Height was ${heightSource}; the stated height of ${patient.heightCm} cm is the value used for the predicted values, so they carry added uncertainty.`);
  if (undisclosedSex && scenario?.referenceSex) note.push(`Predicted values use ${SEX[scenario.referenceSex.used].toLowerCase()} reference equations, the laboratory default; the patient did not disclose sex.`);
  else if (scenario?.referenceSex && scenario.referenceSex.used !== scenario.referenceSex.birth) note.push(`Predicted values use ${SEX[scenario.referenceSex.used].toLowerCase()} reference equations; sex assigned at birth is recorded as ${SEX[scenario.referenceSex.birth].toLowerCase()}.${scenario.referenceSex.note ? ` ${scenario.referenceSex.note}` : ''}`);
  const unavailable = Object.values(m).filter((x) => x.available === false);
  if (unavailable.length) note.push(`No reference value could be computed for ${unavailable.length} measurement${unavailable.length > 1 ? 's' : ''} (${[...new Set(unavailable.map((x) => x.reason))].join('; ')}).`);

  const technologistComments = [...(scenario?.technologistComments ?? []), ...derivedComments(caseData, includeGrades)];

  const model = {
    meta: { caseCode: code, patientId: patientId(d.seed), marker: SIMULATION_MARKER, generatorVersion: GENERATOR_VERSION, equation, hasPost, includeGrades, figureErrors },
    header: { fields },
    sections,
    technologistComments,
    referenceNote: note,
    interpretation: options.interpretationText ?? null,
    interpretationNotes: options.interpretationText ? (options.interpretationNotes ?? []) : [],
    footer: {
      signatureLabel: 'Simulated interpreting physician (not signed)',
      dateLabel: 'Date',
      disclaimer: SIMULATION_DISCLAIMER,
      generator: `PFT Sim generator version ${GENERATOR_VERSION}`,
      caseCode: code,
      marker: SIMULATION_MARKER,
    },
  };

  if (includeKey) {
    const k = interp.key;
    model.sections.push({
      id: 'key', title: 'Answer key (instructor copy)', figures: [], figureIds: [], notes: [],
      tables: [{
        id: 'key', caption: 'Answer key under the displayed spirometry equation',
        columns: [{ key: 'index', label: 'Item', align: 'left' }, { key: 'value', label: 'Key', align: 'left' }],
        rows: [['Pattern', k.pattern], ['Severity', k.severity ?? 'not applicable'], ['FEV1 grade', k.gradeFev1], ['FVC grade', k.gradeFvc], ['Bronchodilator response', k.bronchodilator ?? 'not performed'], ['DLCO', k.dlco ?? 'not performed']].map(([index, value], i) => ({ id: String(i), index, value })),
        footnote: 'Present only when the model is built with includeKey.',
      }],
    });
  }
  return model;
}

/** Every table in the model, in print order. */
export const allTables = (model) => model.sections.flatMap((s) => s.tables);
